package org.gnoseis.data.backup

import org.bouncycastle.crypto.generators.Argon2BytesGenerator
import org.bouncycastle.crypto.params.Argon2Parameters
import org.junit.Assert.assertArrayEquals
import org.junit.Test

/**
 * Checks Bouncy Castle's Argon2id against the test vector in RFC 9106, section 5.3.
 * Bouncy Castle is used directly; no security provider is registered.
 */
class Argon2idKnownAnswerTest {

    @Test
    fun argon2id_matchesRfc9106TestVector() {
        val password = ByteArray(32) { 0x01 }
        val salt = ByteArray(16) { 0x02 }
        val secret = ByteArray(8) { 0x03 }
        val associatedData = ByteArray(12) { 0x04 }

        val parameters = Argon2Parameters.Builder(Argon2Parameters.ARGON2_id)
            .withVersion(Argon2Parameters.ARGON2_VERSION_13)
            .withMemoryAsKB(32)
            .withIterations(3)
            .withParallelism(4)
            .withSalt(salt)
            .withSecret(secret)
            .withAdditional(associatedData)
            .build()

        val tag = ByteArray(32)
        Argon2BytesGenerator().apply { init(parameters) }.generateBytes(password, tag)

        assertArrayEquals(
            hex("0d640df58d78766c08c037a34a8b53c9d01ef0452d75b65eb52520e96b01e659"),
            tag
        )
    }

    private fun hex(text: String): ByteArray =
        ByteArray(text.length / 2) { text.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
}
